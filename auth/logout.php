<?php

/*
|--------------------------------------------------------------------------
| Logout
|--------------------------------------------------------------------------
|
| Safely ends the student's authenticated session and returns them to the
| login page.
|
|--------------------------------------------------------------------------
*/

session_start();


/*
|--------------------------------------------------------------------------
| Remove Session Variables
|--------------------------------------------------------------------------
*/

$_SESSION = [];


/*
|--------------------------------------------------------------------------
| Remove Session Cookie
|--------------------------------------------------------------------------
*/

if (
    ini_get(
        "session.use_cookies"
    )
) {

    $cookieParameters =
        session_get_cookie_params();


    setcookie(
        session_name(),
        "",
        time() - 42000,
        $cookieParameters["path"],
        $cookieParameters["domain"],
        $cookieParameters["secure"],
        $cookieParameters["httponly"]
    );
}


/*
|--------------------------------------------------------------------------
| Destroy Session
|--------------------------------------------------------------------------
*/

session_destroy();


/*
|--------------------------------------------------------------------------
| Return to Login
|--------------------------------------------------------------------------
*/

header(
    "Location: login.php?logged_out=1"
);

exit;